"""Generate the C header and TS constants for the shared LensState array.

Keeps C and TS offsets in lockstep: edit engine/lens/state_fields.txt only.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "engine/lens/state_fields.txt")
OUT_H = os.path.join(ROOT, "engine/lens/lens_state.h")
OUT_JS = os.path.join(ROOT, "build/stage/LensState.js")


def fields():
    out, off = [], 0
    for line in open(SRC):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        name, count = line.split()
        out.append((name, off, int(count)))
        off += int(count)
    return out, off


def main():
    fl, total = fields()
    h = ["// GENERATED by tools/gen_state.py from state_fields.txt. Do not edit.",
         "#pragma once"]
    for name, off, cnt in fl:
        h.append(f"#define LS_{name.upper()} {off}" + (f"  /* x{cnt} */" if cnt > 1 else ""))
    h.append(f"#define LS_COUNT {total}")
    open(OUT_H, "w").write("\n".join(h) + "\n")

    js = ["// GENERATED by tools/gen_state.py from engine/lens/state_fields.txt. Do not edit.",
          "exports.LS = {"]
    for name, off, cnt in fl:
        js.append(f"  {name}: {off},")
    js.append("};")
    js.append(f"exports.LS_COUNT = {total};")
    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    open(OUT_JS, "w").write("\n".join(js) + "\n")
    print(f"gen_state: {len(fl)} fields, {total} ints")


if __name__ == "__main__":
    sys.exit(main())
